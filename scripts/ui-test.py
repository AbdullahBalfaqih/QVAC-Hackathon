"""Browser regression against the running app and real QVAC, using published case text.
Requires Playwright/Chromium and a running model. Validation-only inputs do not represent a worker.
"""
from playwright.sync_api import sync_playwright
from pathlib import Path
import json, hashlib, re
ROOT=Path(__file__).resolve().parent.parent
BASE='http://127.0.0.1:4174'
result={'base':BASE,'suite':'English dark/orange interface','cases':[],'browser_errors':[],'bad_responses':[],'external_requests':[]}

def expect(condition, description):
    if not condition: raise AssertionError(description)
    result['cases'].append(description)

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':1440,'height':960},device_scale_factor=1,accept_downloads=True)
    page=context.new_page()
    page.on('pageerror',lambda e:result['browser_errors'].append(str(e)))
    page.on('response',lambda r:result['bad_responses'].append({'url':r.url,'status':r.status}) if r.status>=400 else None)
    page.on('request',lambda r:result['external_requests'].append(r.url) if not r.url.startswith(BASE) else None)
    page.on('dialog',lambda d:d.accept())
    page.goto(BASE+'/',wait_until='networkidle')
    page.locator('.status-dot.ready').wait_for(timeout=90000)
    expect(page.locator('html').get_attribute('lang')=='en' and page.locator('html').get_attribute('dir')=='ltr','English left-to-right document')
    expect(page.locator('h1').inner_text()=='Workspace.','English workspace renders')
    expect(not re.search(r'[\u0600-\u06ff]',page.locator('body').inner_text()),'Default visible interface and published cases contain no Arabic labels')
    expect(page.locator('.metric-number').all_text_contents()==['9','4','5'],'Lakshmi published counts: 9, 4 and difference 5')
    expect('same source' in page.locator('.source-note').inner_text().lower(),'Same-source evidence warning is visible')
    expect('Remote preview' in page.locator('.preview-banner').inner_text(),'Remote preview privacy warning is visible')
    page.screenshot(path=str(ROOT/'evidence'/'overview-desktop-en.png'),full_page=True)
    page.locator('[data-action="filter-cases"][data-filter="published"]').click()
    expect(page.locator('.case-tile').count()==4,'Published filter shows four sourced historical cases')
    page.locator('[data-action="filter-cases"][data-filter="local"]').click()
    expect(page.locator('.case-tile').count()==0,'Local-case filter does not invent case records')
    page.locator('[data-action="filter-cases"][data-filter="all"]').click()
    page.locator('[data-action="select-case"][data-case-id="published-vikas-2023"]').click()
    expect(page.locator('.metric-number').all_text_contents()==['14','7','7'],'Clicking a case selects its actual sourced counts')
    page.locator('[data-action="select-case"][data-case-id="published-lakshmi-2022"]').click()
    page.locator('[data-view="assistant"]').first.click()
    expect('nine days' in page.locator('#ai-text').input_value(),'Published source passage is prefilled')
    expect(page.locator('#ai-source-type').input_value()=='published' and 'article-14.com' in page.locator('#ai-url').input_value(),'AI source label, type and URL are explicit')
    original_source=page.locator('#ai-source').input_value();original_url=page.locator('#ai-url').input_value()
    page.locator('#ai-source').fill(original_source+' ')
    expect(page.locator('#ai-url').input_value()=='','Changing the source clears the old URL')
    page.locator('#ai-source').fill(original_source);page.locator('#ai-url').fill(original_url)
    page.locator('[data-action="run-ai"]').click()
    page.locator('.candidate').first.wait_for(timeout=120000)
    expect(page.locator('.candidate-value').all_text_contents()==['9','4'],'Real QVAC returned grounded Lakshmi candidates')
    page.screenshot(path=str(ROOT/'evidence'/'assistant-desktop-en.png'),full_page=True)
    page.locator('[data-action="candidate"]').first.click()
    expect(page.locator('#entry-kind').input_value()=='','AI candidate has no automatic classification')
    expect('nine days' in page.locator('#entry-context').input_value(),'Full source context is retained')
    page.locator('#entry-kind').select_option('worked')
    page.locator('#entry-form button[type="submit"]').click()
    expect(page.locator('.evidence').count()==3,'Reviewed candidate added only after manual classification')
    expect('duplicate' in page.locator('.notice').first.inner_text().lower(),'Duplicate aggregate pauses comparison')
    page.locator('[data-view="overview"]').first.click()
    expect('Local case' in page.locator('.case-tile.selected').inner_text(),'Editing a published example demotes it to a local case')
    page.locator('[data-view="records"]').first.click()
    page.locator('.evidence').last.locator('[data-action="delete-entry"]').click()
    expect(page.locator('.evidence').count()==2,'Duplicate entry can be removed')
    page.locator('#case-select').select_option('published-vikas-2023')
    page.locator('[data-view="overview"]').first.click()
    expect(page.locator('.metric-number').all_text_contents()==['14','7','7'],'Vikas public narrative: 14, 7 and difference 7')
    page.locator('[data-view="assistant"]').first.click();page.locator('[data-action="run-ai"]').click()
    page.locator('.candidate').first.wait_for(timeout=120000)
    expect(page.locator('.candidate-value').all_text_contents()==['14','7'],'Real QVAC extracted 14 and 7 from the published quote')
    page.locator('#ai-text').fill(page.locator('#ai-text').input_value()+' ')
    expect(page.locator('.candidate').count()==0,'Editing text invalidates stale AI candidates')
    page.locator('[data-view="report"]').first.click()
    expect(page.locator('[data-action="download-report"]').is_disabled(),'Draft download disabled before explicit review')
    page.locator('#report-reviewed').check()
    with page.expect_download() as download_info:page.locator('[data-action="download-report"]').click()
    dest=ROOT/'evidence'/'automated-test-draft-vikas-en.txt';download_info.value.save_as(str(dest))
    draft=dest.read_text(encoding='utf-8-sig')
    expect('Not sent automatically' in draft and 'not legal advice' in draft,'Downloaded English draft states its actual limits')
    page.locator('#report-text').fill(page.locator('#report-text').input_value()+'\n')
    expect(page.locator('[data-action="download-report"]').is_disabled(),'Editing the draft invalidates review confirmation')
    page.locator('[data-view="overview"]').first.click();page.locator('[data-action="new-case"]').first.click()
    page.locator('#case-title').fill('Validation-only case — not a real worker')
    page.locator('#scope-start').fill('2022-05-01');page.locator('#scope-end').fill('2022-05-15')
    page.locator('#case-form button[type="submit"]').click()
    expect('Validation-only case' in page.locator('.case-tile.selected .case-name').inner_text(),'An empty validation-only case can be created')
    page.locator('[data-view="records"]').first.click();page.locator('[data-action="add-day"]').click()
    page.locator('#day-date').fill('2022-05-16');page.locator('#day-source').fill('Validation-only input')
    page.locator('#day-form button[type="submit"]').click()
    expect('within the case period' in page.locator('#form-error').inner_text(),'Out-of-scope daily date is rejected')
    page.locator('[data-action="close-modal"]').first.click()
    header=b'date,side,status,source\r\n'
    page.locator('#csv-file').set_input_files({'name':'athar-header-only.csv','mimeType':'text/csv','buffer':header})
    expected_hash=hashlib.sha256(header).hexdigest()
    page.locator('#modal').get_by_text('SHA-256: '+expected_hash).wait_for(timeout=10000)
    expect(expected_hash in page.locator('#modal').inner_text(),'CSV byte-level SHA-256 is shown before import')
    expect(page.locator('[data-action="confirm-csv"]').is_disabled(),'Header-only CSV cannot create records')
    page.locator('[data-action="close-modal"]').first.click()
    page.reload(wait_until='networkidle')
    expect('Validation-only case' in page.locator('#case-select').locator('option:checked').inner_text(),'Browser local storage survives reload')
    expect(not result['browser_errors'],'No browser JavaScript errors')
    expect(not result['bad_responses'],f"No failed HTTP responses (including fonts): {result['bad_responses']}")
    expect(not result['external_requests'],'No external browser requests during the workflow')
    mobile=browser.new_context(viewport={'width':375,'height':812},device_scale_factor=1)
    mp=mobile.new_page();mp.goto(BASE+'/',wait_until='networkidle')
    mp.screenshot(path=str(ROOT/'evidence'/'overview-mobile-en.png'),full_page=True)
    dims=mp.evaluate('({scroll:document.documentElement.scrollWidth, inner:window.innerWidth})')
    expect(dims['scroll']<=dims['inner']+1,f'Mobile viewport has no horizontal overflow: {dims}')
    expect(mp.locator('.metric-number').all_text_contents()==['9','4','5'],'Mobile displays the same sourced counts')
    mobile.close();context.close();browser.close()
(ROOT/'evidence'/'ui-test-results-en.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
print(json.dumps(result,ensure_ascii=False,indent=2))
